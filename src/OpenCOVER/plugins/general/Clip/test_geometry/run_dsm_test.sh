#!/bin/bash
# Test the Clip plugin (v2) with a photogrammetry-style DSM scene:
#   - dsm_terrain.osgb : ONE object made of 9 tile geodes (like a real
#     photogrammetry .osgb), buildings modelled as flat-topped spikes that
#     are PART of the surface (a digital surface model)
#   - building1/2.obj  : reference boxes to shape the clip boxes after
#
# This exercises the plugin's multi-geode path: the target is a single scene
# object with many geodes, and the clip shader is injected into every geode
# of the object (including paged/expired tiles, kept in sync per frame).
#
#   ./run_dsm_test.sh               # auto-apply the setup
#   ./run_dsm_test.sh interactive   # start empty; pick with the Clip menu
#
# Extra arguments are passed straight to cover.
#
# The .osgb is generated by generate_test_geometry.py (tiles) +
# build_dsm_osgb.sh (assembly); it is rebuilt automatically if missing.

cd "$(dirname "$0")" || exit 1

MODE="setup"
if [ "${1:-}" = "interactive" ]; then
    MODE="interactive"
    shift
fi

# make sure the OSG reader / plugin dependency libs are reachable
if [ -d /home/hpcmdjur/local_libs/lib ]; then
    case ":$LD_LIBRARY_PATH:" in
        *":/home/hpcmdjur/local_libs/lib:"*) ;;
        *) LD_LIBRARY_PATH="${LD_LIBRARY_PATH:+$LD_LIBRARY_PATH:}/home/hpcmdjur/local_libs/lib" ;;
    esac
    export LD_LIBRARY_PATH
fi

# build the multi-geode .osgb if it is missing (or -f was not given, see below)
if [ ! -f dsm_terrain.osgb ]; then
    echo "dsm_terrain.osgb not found - generating..."
    python3 generate_test_geometry.py || exit 1
    ./build_dsm_osgb.sh || exit 1
fi

STAGE_DIR=".covconfig/plugin"
mkdir -p "$STAGE_DIR"

if [ "$MODE" = "interactive" ]; then
    cp Clip_interactive.toml "$STAGE_DIR/Clip.toml"
else
    cp Clip_dsm_setup.toml "$STAGE_DIR/Clip.toml"
fi

# point the config manager at THIS directory's .covconfig (first in its search
# path), so the staged setup is read deterministically instead of the empty
# installed default
export COVCONFIG="$(pwd)/.covconfig"

# locate the cover launcher
if [ -n "$COVISEDIR" ] && [ -x "$COVISEDIR/bin/cover" ]; then
    COVER="$COVISEDIR/bin/cover"
elif command -v cover >/dev/null 2>&1; then
    COVER="$(command -v cover)"
else
    echo "could not find 'cover' (set COVISEDIR or put it on PATH)" >&2
    exit 1
fi

echo "Clip DSM test (v2): mode=$MODE"
echo "  target: dsm_terrain.osgb (1 object, 9 tile geodes; pre-applied from config in setup mode)"
echo "Launching: $COVER dsm_terrain.osgb building1.obj building2.obj opencover://plugin/Clip $*"
echo
echo "Tip: 'Box from picked object' on building1/2 shapes the clip boxes over"
echo "the DSM spikes (or 'Add box at hit point' directly on the terrain)."
echo
echo "Expected: the DSM shows a hole where each box cuts the surface. Only the"
echo "part of the surface INSIDE a box is removed - the terrain BEHIND a box"
echo "(further down the view ray) stays visible. Ghost cubes are selectable"
echo "and movable; 'Clear' restores the surface."
echo

exec "$COVER" dsm_terrain.osgb building1.obj building2.obj opencover://plugin/Clip "$@"
