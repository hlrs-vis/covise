#!/usr/bin/env python3
# Generates a test scene for the Clip plugin:
#   - terrain.obj   : a wavy heightfield (the "target")
#   - building*.obj : boxes that straddle the surface (the "voids")
#   - dsm_tile_*.obj: a photogrammetry-style DSM heightfield, split into a 3x3
#                     tile grid, with building footprints modelled as flat-topped
#                     spikes that are PART of the surface (like a real DSM)
# The DSM tiles are assembled into one multi-geode object dsm_terrain.osgb
# (one top-level group with one geode per tile), mimicking a photogrammetry
# .osgb model. Run build_dsm_osgb.sh after generating to (re)build it.
# Pure standard library, no dependencies.
#
# Load with:  cover terrain.obj building1.obj building2.obj
# or:        cover dsm_terrain.osgb building1.obj building2.obj
# then use the Clip menu to pick the terrain as target and the boxes as voids.

import math
import os

OUT = os.path.dirname(os.path.abspath(__file__))


def write_obj(path, verts, faces):
    with open(path, "w") as f:
        f.write("# generated by generate_test_geometry.py\n")
        for (x, y, z) in verts:
            f.write("v %.4f %.4f %.4f\n" % (x, y, z))
        for face in faces:
            f.write("f %s\n" % " ".join(str(i) for i in face))
    print("wrote %s (%d verts, %d faces)" % (path, len(verts), len(faces)))


def terrain():
    n = 40                      # cells per side
    extent = 10.0               # x/y in [-extent, extent]

    def height(x, y):
        mound = 1.6 * math.exp(-(x * x + y * y) / 40.0)
        ripple = 0.35 * math.sin(x / 2.0) * math.cos(y / 2.0)
        return mound + ripple

    verts = []
    for j in range(n + 1):
        for i in range(n + 1):
            x = -extent + 2.0 * extent * i / n
            y = -extent + 2.0 * extent * j / n
            verts.append((x, y, height(x, y)))

    def idx(i, j):
        return j * (n + 1) + i + 1  # 1-based

    faces = []
    for j in range(n):
        for i in range(n):
            faces.append((idx(i, j), idx(i + 1, j), idx(i + 1, j + 1), idx(i, j + 1)))

    write_obj(os.path.join(OUT, "terrain.obj"), verts, faces)


def box(path, cx, cy, zmin, zmax, sx, sy):
    hx, hy = sx / 2.0, sy / 2.0
    # 8 corners: 0-3 bottom, 4-7 top
    verts = [
        (cx - hx, cy - hy, zmin), (cx + hx, cy - hy, zmin),
        (cx + hx, cy + hy, zmin), (cx - hx, cy + hy, zmin),
        (cx - hx, cy - hy, zmax), (cx + hx, cy - hy, zmax),
        (cx + hx, cy + hy, zmax), (cx - hx, cy + hy, zmax),
    ]
    faces = [
        (1, 2, 3, 4),   # bottom
        (5, 6, 7, 8),   # top
        (1, 2, 6, 5),   # front
        (2, 3, 7, 6),   # right
        (3, 4, 8, 7),   # back
        (4, 1, 5, 8),   # left
    ]
    write_obj(os.path.join(OUT, path), verts, faces)


# Building footprints for the DSM: (cx, cy, half_w, half_h, top_height).
# Kept slightly inside the matching void boxes (building1: 3x3 @ (0,0),
# building2: 2.5x2.5 @ (5,-4)) so the voids fully cover the spikes.
DSM_BUILDINGS = [
    (0.0, 0.0, 1.1, 1.1, 5.5),
    (5.0, -4.0, 0.9, 0.9, 3.8),
    (-6.0, 5.0, 1.4, 1.0, 4.6),   # a third spike without a void box
]


def dsm_height(x, y):
    # base surface (same family as terrain()) + flat-topped building spikes
    h = 1.6 * math.exp(-(x * x + y * y) / 40.0) + 0.35 * math.sin(x / 2.0) * math.cos(y / 2.0)
    for (cx, cy, hw, hh, top) in DSM_BUILDINGS:
        # signed Chebyshev distance to the building footprint rectangle
        d = max(abs(x - cx) - hw, abs(y - cy) - hh)
        if d < 0.0:
            h = max(h, top)  # inside the footprint: flat top
        elif d < 0.3:
            # short ramp from the surface up to the roof edge
            t = 1.0 - d / 0.3
            h = max(h, h + (top - h) * t * t * (3.0 - 2.0 * t))
    return h


def dsm_tiles(cells_per_side=32):
    n = 40                      # cells per side over the whole extent
    extent = 10.0               # x/y in [-extent, extent]
    tiles = 3                   # tiles per axis -> tiles*tiles geodes

    def tile_origin(t):
        return -extent + 2.0 * extent * t / tiles

    for ty in range(tiles):
        for tx in range(tiles):
            verts = []
            for j in range(cells_per_side + 1):
                for i in range(cells_per_side + 1):
                    x = tile_origin(tx) + (2.0 * extent / tiles) * i / cells_per_side
                    y = tile_origin(ty) + (2.0 * extent / tiles) * j / cells_per_side
                    verts.append((x, y, dsm_height(x, y)))

            def idx(i, j):
                return j * (cells_per_side + 1) + i + 1  # 1-based

            faces = []
            for j in range(cells_per_side):
                for i in range(cells_per_side):
                    faces.append((idx(i, j), idx(i + 1, j), idx(i + 1, j + 1), idx(i, j + 1)))

            write_obj(os.path.join(OUT, "dsm_tile_%d_%d.obj" % (tx, ty)), verts, faces)


if __name__ == "__main__":
    terrain()
    # boxes straddle the surface: part below, part above, so the terrain is cut
    box("building1.obj", 0.0, 0.0, -1.0, 7.0, 3.0, 3.0)   # on the mound peak
    box("building2.obj", 5.0, -4.0, -1.0, 4.5, 2.5, 2.5)  # on a slope
    dsm_tiles()
